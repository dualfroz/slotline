CREATE TABLE resource_group (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT       NOT NULL,
    parent_group_id BIGINT,
    name            VARCHAR(128) NOT NULL,
    created_at      TIMESTAMP    NOT NULL,
    CONSTRAINT fk_group_org FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT fk_group_parent FOREIGN KEY (parent_group_id) REFERENCES resource_group (id)
);
CREATE INDEX idx_group_org ON resource_group (organization_id);

