CREATE TABLE operating_hours (
    id          BIGINT     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id BIGINT     NOT NULL,
    day_of_week VARCHAR(9) NOT NULL,
    open_time   TIME       NOT NULL,
    close_time  TIME       NOT NULL,
    CONSTRAINT fk_hours_resource FOREIGN KEY (resource_id) REFERENCES resource (id)
);
CREATE INDEX idx_hours_resource ON operating_hours (resource_id);

CREATE TABLE blackout_date (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id BIGINT       NOT NULL,
    start_date  DATE         NOT NULL,
    end_date    DATE         NOT NULL,
    reason      VARCHAR(256),
    CONSTRAINT fk_blackout_resource FOREIGN KEY (resource_id) REFERENCES resource (id)
);
CREATE INDEX idx_blackout_resource ON blackout_date (resource_id);

CREATE TABLE waitlist_entry (
    id                      BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id             BIGINT      NOT NULL,
    organization_id         BIGINT      NOT NULL,
    user_id                 BIGINT      NOT NULL,
    start_time              TIMESTAMP   NOT NULL,
    end_time                TIMESTAMP   NOT NULL,
    status                  VARCHAR(16) NOT NULL,
    created_at              TIMESTAMP   NOT NULL,
    promoted_reservation_id BIGINT,
    CONSTRAINT fk_waitlist_resource FOREIGN KEY (resource_id) REFERENCES resource (id),
    CONSTRAINT fk_waitlist_org FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT fk_waitlist_user FOREIGN KEY (user_id) REFERENCES app_user (id)
);
CREATE INDEX idx_waitlist_resource_status ON waitlist_entry (resource_id, status);
